export function createThemePalette(
	overrides: Partial<ThemePalette>,
	mode: "light" | "dark" = "light",
): ThemePalette {
	const base = mode === "dark" ? darkThemePalette : baseThemePalette;
	return { ...base, ...overrides };
}

